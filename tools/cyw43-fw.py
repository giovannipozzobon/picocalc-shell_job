#!/usr/bin/env python3
"""cyw43-fw.py — the CYW43439's firmware as a file, for the shell to read
from the card instead of holding it in RAM (design.md §3.10).

    cyw43-fw.py SDK-HEADER OUT.bin OUT.h

SDK-HEADER is the Pico SDK's own C array (lib/cyw43-driver/firmware/
wb43439A0_7_95_49_00_combined.h, the one with Bluetooth). OUT.bin has the
array's bytes as they are: the Wi-Fi firmware, padded to 512, then the CLM
blob. OUT.h is the header `cyw43_ll.c` includes in place of the array (the
patch in cmake/cyw43_fw.cmake): the two lengths, the file's length, and
the hook that reads it. The lengths come from the SDK header, so the file
and the program built with it always agree.
"""
import re
import sys


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, out_bin, out_h = sys.argv[1:]
    text = open(src).read()
    wifi = int(re.search(r"#define\s+CYW43_WIFI_FW_LEN\s+\((\d+)\)", text).group(1))
    clm = int(re.search(r"#define\s+CYW43_CLM_LEN\s+\((\d+)\)", text).group(1))
    start = text.index("{", text.index("[]"))
    end = text.index("};", start)
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", text[start:end]))
    want = ((wifi + 511) // 512) * 512 + clm
    if len(data) != want:
        sys.exit(f"{src}: the array has {len(data)} bytes, not {want} "
                 f"(Wi-Fi {wifi} to a multiple of 512, then CLM {clm})")
    open(out_bin, "wb").write(data)
    open(out_h, "w").write(f"""/* cyw43_fw_stream.h — generated by tools/cyw43-fw.py from
 * {src.split('/')[-1]}: do not edit.
 *
 * In place of the SDK's firmware array, for a program built with
 * CYW43_FW_STREAM (cmake/cyw43_fw.cmake): `fw_data` is an address no
 * memory has, and cyw43_ll.c reads what it points to through
 * cyw43_fw_read(), from the file this was made with (design.md §3.10). */
#ifndef CYW43_FW_STREAM_H
#define CYW43_FW_STREAM_H

#include <stddef.h>
#include <stdint.h>

#define CYW43_WIFI_FW_LEN ({wifi})
#define CYW43_CLM_LEN ({clm})
#define CYW43_FW_FILE_LEN ({want})
#define CYW43_FW_VIRTUAL 0xa0000000u

static const uintptr_t fw_data = CYW43_FW_VIRTUAL;

/* `len` bytes at `offset` in the file: 0, or nonzero if it could not be
 * read. The program's (src/port/cyw43_fw.c). */
int cyw43_fw_read(uint32_t offset, void *dst, size_t len);

#endif /* CYW43_FW_STREAM_H */
""")
    print(f"cyw43-fw: {out_bin}, {want} bytes (Wi-Fi {wifi}, CLM {clm})")


if __name__ == "__main__":
    main()
